    public static readonly bool[,,] Font5x7 = new bool[128, 5, 7];
    public static readonly Dictionary<char, bool[,]> Font5x7Map = new Dictionary<char, bool[,]>();

        static Font()
        {
            // Map ASCII 32..126 to chars
            for (int ch = 0; ch < Font5x7Data.Length; ch++)
            {
                var charData = Font5x7Data[ch];
                if (charData == null) continue;
                int ascii = ch + 32;
                var glyph = new bool[5, 7];
                for (int y = 0; y < 7; y++)
                {
                    byte row = charData[y];
                    for (int x = 0; x < 5; x++)
                    {
                        bool bit = ((row >> (4 - x)) & 1) != 0;
                        Font5x7[ch, x, y] = bit;
                        glyph[x, y] = bit;
                    }
                }
                Font5x7Map[(char)ascii] = glyph;
            }
        }
    }
